-- ── מה זה מתקן ──────────────────────────────────────────────────────────────
--
-- BE (Bloom Energy) נסחר ב-NYSE ⇒ נייר **דולרי**. מסלול הכתיבה חתם על השורה
-- `currency = capitalCurrency`, וההון של החשבון הזה שקלי ⇒ השורה תויגה `ILS`.
-- זו ⛔ אינה מדידה של השוק, היא **העדפת חשבון שנרשמה כנתון**.
--
-- ⇒ `deriveInstrumentCurrency` גוזר `CONTRADICTED` ("ils_never_measured"),
--   העסקה מוחרגת ממצרפי כסף, ועל המסך מופיע צ'יפ "מטבע לא מאומת". התיקון
--   מחזיר את התווית למה שהשוק בפועל אומר ⇒ הנייר נכנס חזרה לחשבון ומומר.
--
-- ── למה זה נזק-אפס ──────────────────────────────────────────────────────────
--
--   • שורה **אחת**, של ניב עצמו (`92a0…`), חשבון הצילום. ⛔ אין משתמש אחר.
--   • ⛔ **אף מחיר לא נוגע.** `entry` · `exit` · `stop` · `shares` נשארים
--     בדיוק כפי שהם. משתנה **תווית** בלבד. זה ההפך המדויק מ-13 שורות ת"א,
--     שם התווית לבדה הייתה משקרת בלי חלוקה ב-100 (⇒ ⛔ לא נגענו בהן).
--   • הפיך במשפט אחד (למטה), ⛔ בלי גיבוי ו-⛔ בלי חלון תחזוקה.
--
-- ⚠️ ⛔ **אל תרחיב את ה-`UPDATE` הזה לשורות נוספות.** כל שורה אחרת דורשת
--    מדידה נפרדת של הבורסה שבה הנייר נסחר. `WHERE` נעול על טיקר **ומטבע**
--    כדי שריצה כפולה תהיה no-op.
-- ─────────────────────────────────────────────────────────────────────────────

-- ── 1 · SELECT לפני — הדביקו את הפלט לפני שמריצים את ה-UPDATE ───────────────
select id, user_id, ticker, currency, entry, stop, exit, shares, status, date
from   public.trades
where  upper(ticker) = 'BE'
order  by date;

-- ציפייה: שורה אחת, currency = 'ILS'. אם חזרו כמה שורות או currency אחר —
-- ⛔ עצרו ודווחו. ⛔ אל תריצו את ה-UPDATE "כדי לראות מה יקרה".

-- ── 2 · UPDATE ──────────────────────────────────────────────────────────────
update public.trades
set    currency = 'USD'
where  upper(ticker) = 'BE'
  and  currency = 'ILS';

-- ציפייה: UPDATE 1.

-- ── 3 · SELECT אחרי ─────────────────────────────────────────────────────────
select id, ticker, currency, entry, stop, exit, shares
from   public.trades
where  upper(ticker) = 'BE';

-- ציפייה: אותה שורה, אותם מספרים בדיוק, currency = 'USD'.
